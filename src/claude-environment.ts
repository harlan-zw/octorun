/** Keep stored-login settings. Exclude controller secrets, injected code, and alternate authentication or backend settings. */
export function claudeEnvironment(source: NodeJS.ProcessEnv): NodeJS.ProcessEnv {
  return Object.fromEntries(inheritedVariables.flatMap(name => source[name] === undefined ? [] : [[name, source[name]]]))
}
